import { checkGcode, DEFAULT_ALLOWED, PLA_LIMITS } from '@gkod/checks';
import { describe, expect, it } from 'vitest';
import { createPostProcessor, END_BEGINS, kiriExtrudeAbs, START_DONE } from './postprocess';
import { DEFAULT_PRINTER_ID, findPrinter, type KiriDevice, PLA, printerFacts, printers } from './printers';

// Output in the shape Kiri:Moto writes it: preamble, start code, a retract, numbered layers, end code.
function fakeKiri(device: KiriDevice, layers: number): string[] {
  const abs = kiriExtrudeAbs(device);
  let e = 0;
  const E = (de: number) => (abs ? (e += de) : de).toFixed(4);
  const cx = device.bedWidth / 2;
  const cy = device.bedDepth / 2;
  const out = ['; Generated by Kiri:Moto 4.7.4', '; --- process ---', '; sliceHeight = 0.2', '; --- startup ---'];
  out.push(...device.gcodePre, `G1 E${E(-2)} F2400 ; e-retract 2`);
  for (let n = 0; n < layers; n++) {
    const z = (0.2 * (n + 1)).toFixed(1);
    out.push(
      `;; --- layer ${n} (0.200 @ ${z}) ---`,
      `G0 Z${z} F4800`,
      `G0 X${cx - 10} Y${cy - 10}`,
      `G1 E${E(2)} F2400 ; e-engage 2`,
      `G1 X${cx + 10} Y${cy - 10} E${E(0.8)} F1800`,
      `G1 X${cx + 10} Y${cy + 10} E${E(0.8)}`,
      `G1 E${E(-2)} F2400 ; e-retract 2`,
    );
  }
  out.push(...device.gcodePost, '; --- filament used: 16 mm ---', '; --- print time: 60s ---');
  return out;
}

function processed(device: KiriDevice, layers = 10): string {
  const lines: string[] = [];
  const post = createPostProcessor({ extrudeAbs: kiriExtrudeAbs(device) }, (line) => lines.push(line));
  for (const line of fakeKiri(device, layers)) post.line(line);
  return lines.join('\n');
}

describe('printers', () => {
  it('lists the Kobra 2 Neo first, as the default', () => {
    expect(printers[0]!.id).toBe(DEFAULT_PRINTER_ID);
    expect(printers[0]).toMatchObject({ name: 'Anycubic Kobra 2 Neo', bed: { x: 220, y: 220, z: 250 } });
    expect(findPrinter(DEFAULT_PRINTER_ID)).toBe(printers[0]);
    expect(new Set(printers.map((p) => p.id)).size).toBe(printers.length);
    expect(printers.map((p) => p.name)).toContain('Other printer, 220 x 220 mm, Marlin');
  });

  it('prints PLA inside the safe ranges', () => {
    expect(PLA.nozzle).toBeGreaterThanOrEqual(PLA_LIMITS.nozzleMin);
    expect(PLA.nozzle).toBeLessThanOrEqual(PLA_LIMITS.nozzleMax);
    expect(PLA.bed).toBeLessThanOrEqual(PLA_LIMITS.bedMax);
  });

  for (const printer of printers) {
    describe(printer.name, () => {
      const facts = printerFacts(printer.id)!;
      const device = facts.device;

      it('builds the slicer profile from the printer facts', () => {
        expect(printer.device).toEqual(device);
        expect([device.bedWidth, device.bedDepth, device.maxHeight]).toEqual([printer.bed.x, printer.bed.y, printer.bed.z]);
        expect(device.extruders).toEqual([{ extFilament: 1.75, extNozzle: 0.4, extOffsetX: 0, extOffsetY: 0 }]);
        expect(device.gcodeFan).toEqual([]);
        expect(printer.source).toMatch(/^https:\/\/github\.com\/[^ ]+\/blob\/[0-9a-f]{40}\//);
        expect(facts.gcodeSource).toMatch(/^https:\/\/github\.com\/[^ ]+\/blob\/[0-9a-f]{40}\//);
      });

      it('fills every value in its start and end code itself', () => {
        const lines = [...device.gcodePre, ...device.gcodePost];
        expect(lines.filter((line) => /[{}[\]]/.test(line))).toEqual([]);
        expect(device.gcodePre.at(-1)).toBe(START_DONE);
        expect(device.gcodePost[0]).toBe(END_BEGINS);
        expect(lines.join('\n')).toContain(`S${PLA.nozzle}`);
      });

      it('states the same extruder mode it gives the slicer', () => {
        expect(kiriExtrudeAbs(device)).toBe(device.extrudeAbs);
        const modes = device.gcodePre.filter((line) => /^M8[23]\b/.test(line));
        expect(modes).toEqual([device.extrudeAbs ? expect.stringMatching(/^M82/) : expect.stringMatching(/^M83/)]);
      });

      it('passes the G-code safety check with a sliced body', () => {
        const report = checkGcode(processed(device), { bed: printer.bed, ...PLA_LIMITS, allowed: DEFAULT_ALLOWED });
        expect(report.problems).toEqual([]);
        expect(report.stats.fanOnLayer).toBe(2);
        expect(report.stats.extruderMode).toBe(device.extrudeAbs ? 'absolute' : 'relative');
        expect(report.stats.nozzle).toEqual([PLA.nozzle, 0]);
        expect(report.stats.bed).toEqual([PLA.bed, 0]);
      });
    });
  }
});
